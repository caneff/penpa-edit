const recordedHeader = (recording) => JSON.parse(readFileSync(new URL(`./recordings/${recording}.steps.json`, import.meta.url), 'utf8')).header

// The entries the review page lists: `SPEC` with each one's solve link, the `#` part, filled in.
export async function galleryEntries (browser) {
  return Promise.all(SPEC.map(async ({ recording, build, ...entry }) => {
    if (!recording) return { ...entry, link: await build(browser) }
    const { source, gridtype } = recordedHeader(recording)
    return { ...entry, gridtype, link: source }
  }))
}

// The text of `docs/gallery-puzzles.js`: a classic script, since a module does not load over `file://`.
export function renderGalleryFile (entries) {
  return '// Generated by `node live/generate-gallery.mjs` from `live/gallery-puzzles.mjs`; edit that, not this.\n' +
    `const GALLERY_PUZZLES = [\n${entries.map((e) => `  ${JSON.stringify(e)}`).join(',\n')}\n]\n`
}
